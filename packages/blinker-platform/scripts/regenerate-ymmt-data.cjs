#!/usr/bin/env node
// Regenerate packages/utils/ymmt-data.js from the StoneEagle YMMT
// reference CSV. Run after a SEFI YMMT update lands.
//
// Usage:
//   node scripts/regenerate-ymmt-data.js <path-to-csv> [minYear]
//
// CSV columns: idx, Year, Make, Model, Trim, Style, Asset Type
// Output shape (matches existing packages/utils/ymmt-data.js exports):
//   YEARS                 → number[] descending
//   YMMT_RAW              → JSON literal of YMMT_DATA
//   YMMT_DATA             → { Make: { Model: [trim, …] } }
//   YMMT_MAKES            → string[]
//   YMMT_YEAR_CONSTRAINTS → { Make: { Model: [minYear, maxYear] | null } }
//   YMMT_ASSET_TYPE       → { Make: { Model: 'P'|'T'|'AL' } } (NEW Wave 23-fu2)
//
// Asset Type is per (Make, Model) — verified to be stable across Year+Trim
// in the SEFI reference (no model has mixed P/T/AL across years/trims).
// If a future CSV breaks that invariant, this script throws with the
// offending key so we can decide whether to widen the lookup to (Year,
// Make, Model, Trim).

const fs = require('fs');
const path = require('path');

const csvPath = process.argv[2];
const MIN_YEAR = parseInt(process.argv[3] || '2000', 10);

if (!csvPath) {
  console.error('usage: node regenerate-ymmt-data.js <csv> [minYear]');
  process.exit(1);
}

const raw = fs.readFileSync(csvPath, 'utf8');
const lines = raw.split(/\r?\n/).filter(Boolean);
const header = lines.shift();
if (!/idx,Year,Make,Model,Trim,Style,Asset Type/i.test(header)) {
  console.error('unexpected header: ' + header);
  process.exit(2);
}

const titleCase = (s) =>
  s.toLowerCase().replace(/\b([a-z])/g, (m) => m.toUpperCase());

const YMMT_DATA = {};
const YMMT_ASSET_TYPE = {};
const YMMT_YEAR_CONSTRAINTS = {};
const yearSet = new Set();
const conflicts = [];

for (const line of lines) {
  // CSV is comma-separated with no quoted fields needing escaping in the
  // SEFI reference; a permissive split is fine.
  const parts = line.split(',');
  if (parts.length < 7) continue;
  const [, yearStr, makeRaw, modelRaw, trimRaw, , assetTypeRaw] = parts;
  const year = parseInt(yearStr, 10);
  if (!Number.isFinite(year) || year < MIN_YEAR) continue;
  const make = titleCase(makeRaw.trim());
  const model = titleCase(modelRaw.trim());
  const trim = trimRaw.trim() ? titleCase(trimRaw.trim()) : null;
  const assetType = (assetTypeRaw || '').trim().toUpperCase();
  if (!make || !model) continue;

  yearSet.add(year);

  YMMT_DATA[make] = YMMT_DATA[make] || {};
  YMMT_DATA[make][model] = YMMT_DATA[make][model] || [];
  if (trim && !YMMT_DATA[make][model].includes(trim)) {
    YMMT_DATA[make][model].push(trim);
  }

  if (assetType && ['P', 'T', 'AL'].includes(assetType)) {
    YMMT_ASSET_TYPE[make] = YMMT_ASSET_TYPE[make] || {};
    const prev = YMMT_ASSET_TYPE[make][model];
    if (prev && prev !== assetType) {
      conflicts.push({ make, model, prev, next: assetType });
    } else {
      YMMT_ASSET_TYPE[make][model] = assetType;
    }
  }

  YMMT_YEAR_CONSTRAINTS[make] = YMMT_YEAR_CONSTRAINTS[make] || {};
  const cur = YMMT_YEAR_CONSTRAINTS[make][model];
  if (!cur) {
    YMMT_YEAR_CONSTRAINTS[make][model] = [year, year];
  } else {
    cur[0] = Math.min(cur[0], year);
    cur[1] = Math.max(cur[1], year);
  }
}

if (conflicts.length) {
  console.error('AssetType conflicts within (Make, Model):');
  for (const c of conflicts.slice(0, 10)) console.error(JSON.stringify(c));
  console.error(`Total: ${conflicts.length}. Falling back: keeping FIRST seen.`);
}

// Sort trims within each model for stable diffs.
for (const make of Object.keys(YMMT_DATA)) {
  for (const model of Object.keys(YMMT_DATA[make])) {
    YMMT_DATA[make][model].sort();
  }
}

// Sort year-constraints map: discontinued models (lastYear < maxYear-2)
// land as bounded ranges; still-current models stay as null.
const maxYear = Math.max(...yearSet);
for (const make of Object.keys(YMMT_YEAR_CONSTRAINTS)) {
  for (const model of Object.keys(YMMT_YEAR_CONSTRAINTS[make])) {
    const [first, last] = YMMT_YEAR_CONSTRAINTS[make][model];
    if (last >= maxYear - 1) {
      YMMT_YEAR_CONSTRAINTS[make][model] = null;
    } else {
      YMMT_YEAR_CONSTRAINTS[make][model] = [first, last];
    }
  }
}

const YEARS = Array.from(yearSet).sort((a, b) => b - a);
const YMMT_MAKES = Object.keys(YMMT_DATA).sort();

const fileBody = `// YMMT (Year/Make/Model/Trim) reference data — regenerated by
// scripts/regenerate-ymmt-data.js from the SEFI YMMT reference CSV.
// DO NOT hand-edit. To refresh, run:
//   node scripts/regenerate-ymmt-data.js <path-to-csv> [minYear]
//
// Source CSV: stoneeagle_ymmt_reference17APR2026.csv (received 2026-05-09).
// Year range: ${MIN_YEAR}–${maxYear} (capped per Wave 23-fu2 decision —
// older long-tail dropped to control bundle size).
// Style column dropped per Wave 23-fu2 decision (52,457 of 56,137 rows
// blank in source; remaining values are trim-suffix strings that don't
// drive SE rate selection).
//
// Wave 23-fu2 (2026-05-09) — Asset Type column added per (Make, Model).
// Three values from SEFI: 'P' (passenger), 'T' (truck/SUV/van/anything
// that's not a car), 'AL' (antique/limited; niche). Stable across
// Year+Trim within each model in the reference (no conflicts at regen).

export const YEARS = ${JSON.stringify(YEARS)};

export const YMMT_RAW = ${JSON.stringify(JSON.stringify(YMMT_DATA))};

export const YMMT_DATA = JSON.parse(YMMT_RAW);

export const YMMT_MAKES = ${JSON.stringify(YMMT_MAKES)};

export const YMMT_YEAR_CONSTRAINTS = ${JSON.stringify(YMMT_YEAR_CONSTRAINTS)};

// Wave 23-fu2 — per-(Make, Model) AssetType code from SEFI YMMT
// reference. Consumed by packages/integrations/product_admin/stoneeagle.js
// SOAP envelope builder so YMMT-only flows (no VIN) ship the correct
// AssetType to SE GetRates instead of the previous hardcoded 'T'.
export const YMMT_ASSET_TYPE = ${JSON.stringify(YMMT_ASSET_TYPE)};

export function getMakes() {
  return YMMT_MAKES;
}

export function getModelsForYearMake(year, make) {
  if (!make || !YMMT_DATA[make]) return [];
  const allModels = Object.keys(YMMT_DATA[make]).sort();
  if (!year) return allModels;
  return allModels.filter((model) => {
    const constraint = YMMT_YEAR_CONSTRAINTS[make]?.[model];
    if (!constraint) return true;
    return year >= constraint[0] && year <= constraint[1];
  });
}

export function getTrimsForYearMakeModel(year, make, model) {
  if (!make || !model || !YMMT_DATA[make]?.[model]) return [];
  return YMMT_DATA[make][model];
}

// Wave 23-fu2 — resolve AssetType for a (make, model) pair. Returns
// 'P' | 'T' | 'AL' or null when unknown. Caller (stoneeagle.js) defaults
// to 'P' when null since passenger covers the most common consumer
// vehicle.
export function getAssetTypeForMakeModel(make, model) {
  if (!make || !model) return null;
  const titleMake = make
    .toLowerCase()
    .replace(/\\b([a-z])/g, (m) => m.toUpperCase());
  const titleModel = model
    .toLowerCase()
    .replace(/\\b([a-z])/g, (m) => m.toUpperCase());
  return YMMT_ASSET_TYPE[titleMake]?.[titleModel] || null;
}
`;

const outPath = path.join(__dirname, '..', 'packages', 'utils', 'ymmt-data.js');
fs.writeFileSync(outPath, fileBody);

console.log(`Wrote ${outPath}`);
console.log(`Years: ${YEARS[YEARS.length - 1]}–${YEARS[0]} (${YEARS.length} years)`);
console.log(`Makes: ${YMMT_MAKES.length}`);
let modelCount = 0;
for (const m of YMMT_MAKES) modelCount += Object.keys(YMMT_DATA[m]).length;
console.log(`Models: ${modelCount}`);
let assetCounts = { P: 0, T: 0, AL: 0 };
for (const make of Object.keys(YMMT_ASSET_TYPE)) {
  for (const model of Object.keys(YMMT_ASSET_TYPE[make])) {
    assetCounts[YMMT_ASSET_TYPE[make][model]]++;
  }
}
console.log(`AssetType: P=${assetCounts.P} T=${assetCounts.T} AL=${assetCounts.AL}`);
